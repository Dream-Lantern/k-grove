function text(x,y,s,size=20,color='#475569',weight=400){svg.push(`<text x="${x}" y="${y}" font-size="${size}" fill="${color}" font-weight="${weight}">${esc(s)}</text>`)}
function box(x,y,w,h,title,lines=[],tone='blue'){
  svg.push(`<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="12" fill="${palette[tone][0]}" stroke="${palette[tone][1]}" stroke-opacity=".4"/>`)
  text(x+20,y+34,title,23,'#0F172A',650); lines.forEach((s,i)=>text(x+20,y+66+i*28,s))
}
function arrow(d,tone='blue',dashed=false){svg.push(`<path d="${d}" fill="none" stroke="${palette[tone][1]}" stroke-width="2.3" ${dashed?'stroke-dasharray="7 5"':''} marker-end="url(#${tone})"/>`)}
function begin(title,sub,h){
  svg=[`<svg xmlns="http://www.w3.org/2000/svg" width="1440" height="${h}" viewBox="0 0 1440 ${h}" role="img" aria-labelledby="title desc"><title id="title">${esc(title)}</title><desc id="desc">${esc(sub)}</desc><defs>`]
  for(const [n,[,c]]of Object.entries(palette))svg.push(`<marker id="${n}" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto"><path d="M0 0L10 5L0 10Z" fill="${c}"/></marker>`)
  svg.push(`</defs><rect width="1440" height="${h}" fill="white"/><g font-family="Microsoft YaHei,Segoe UI,sans-serif">`)
  text(40,48,title,30,'#0F172A',700);text(40,85,sub,20)
}
function save(name){svg.push('</g></svg>');fs.writeFileSync(dir+name+'.svg',svg.join('\n')+'\n')}

